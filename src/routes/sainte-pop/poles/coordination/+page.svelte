	<h1>Pôle Coordination</h1>
	<p class="pole-lead">
		Le pôle Coordination s'occupe de l'organisation du mouvement. Il fait le lien entre les pôles et
		veille à ce que les décisions prises collectivement soient suivies d'effet.
	</p>

	<h2>Ce qu'il fait</h2>
	<ul>
		<li>Prépare le calendrier des réunions et des assemblées, avec leurs ordres du jour.</li>
		<li>
			Rédige et diffuse les comptes rendus pour que chacun et chacune ait accès aux décisions.
		</li>
		<li>Répartit les tâches entre les pôles et suit leur avancement.</li>
		<li>Accueille les nouvelles personnes et les oriente vers le pôle qui leur correspond.</li>
		<li>Gère les outils d'organisation interne : agenda partagé, groupes de discussion.</li>
	</ul>

	<h2>S'impliquer</h2>
	<p>
		Vous aimez organiser, faire circuler l'information et faire avancer les projets collectifs ? Le
		pôle Coordination a besoin de vous.
	</p>
